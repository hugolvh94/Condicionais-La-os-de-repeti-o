print('Um carro sai de uma estação de trem com 50km/h rodados num horário de 15h. Ele vai até o outro lado da cidade e passa por um posto a 300km/hm as 18h. Defina a sua velocidade média.')

delta_s = int(input('Digite o valor de delta s:'))
delta_t = int(input('Digite o valor de delta t:'))


velocidade = delta_s / delta_t

print('O valor da velocidade média é igual a:', velocidade, 'Km/h')